def get_intent_detection_prompt(user_message: str, user_goals: list = None) -> str:
    """Получить промпт для определения намерений"""
    goals_context = ""
    if user_goals:
        goals_list = "\n".join([f"- {g.get('title', 'Без названия')}" for g in user_goals])
        goals_context = f"\n\nТекущие цели пользователя:\n{goals_list}"
    
    return INTENT_DETECTION_PROMPT_TEMPLATE.format(
        goals_context=goals_context,
        user_message=user_message
    )

def get_goal_extraction_prompt(user_message: str) -> str:
    """Получить промпт для извлечения целей"""
    return GOAL_EXTRACTION_PROMPT_TEMPLATE.format(user_message=user_message)

def get_product_recommendation_prompt(user_message: str, context: str) -> str:
    """Получить промпт для рекомендации продуктов"""
    return PRODUCT_RECOMMENDATION_PROMPT_TEMPLATE.format(
        context=context,
        user_message=user_message
    )

def get_proactive_notification_prompt(notification_type: str) -> str:
    """Получить промпт для проактивного уведомления"""
    return PROACTIVE_NOTIFICATION_PROMPTS.get(notification_type, "")

